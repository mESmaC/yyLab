"""CDAS-compatible corpus inventory and evidence for yyLab ingestion.

This is a clean integration of the contracts proven in the local CDAS corpus
workbench: stable identities, minimal source normalization, immutable asset
observations, independent quality evidence, and an explicit selection decision.
Training shards remain compact; the detailed evidence lives in a per-corpus
SQLite sidecar so it can be inspected without feeding metadata to the model.
"""

