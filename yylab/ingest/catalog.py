def _clamp(value: float) -> float:
    return max(0.0, min(1.0, value))


def digest_stream(stream: BinaryIO, *, chunk_size: int = 8 * 1024 * 1024) -> str:
    digest = sha256()
    while chunk := stream.read(chunk_size):
        digest.update(chunk)
    return digest.hexdigest()


def digest_file(path: Path) -> str:
    with path.open("rb") as stream:
        return digest_stream(stream)


def digest_text(text: str) -> str:
    return sha256(text.encode("utf-8")).hexdigest()


def source_digest(source_text: str) -> tuple[str, int]:
    """Return ``(normalized_sha256, utf8_bytes)`` of the minimally normalized source."""

    encoded = normalize_source_text(source_text).encode("utf-8")
    return sha256(encoded).hexdigest(), len(encoded)


def stable_identity(kind: str, *parts: str) -> str:
    """Return the same versioned, length-delimited identity contract as CDAS."""

    digest = sha256()
    digest.update(f"cdas-identity-v{IDENTITY_VERSION}\0{kind}\0".encode())
    for part in parts:
        encoded = part.encode("utf-8")
        digest.update(len(encoded).to_bytes(8, "big"))
        digest.update(encoded)
    return f"{kind}_v{IDENTITY_VERSION}_{digest.hexdigest()[:32]}"


def normalize_source_text(text: str) -> str:
    """Minimal content normalization: remove BOM and canonicalize newlines only."""

    if text.startswith("\ufeff"):
        text = text[1:]
    return text.replace("\r\n", "\n").replace("\r", "\n")


def document_logical_path(asset_logical_path: str, metadata: object) -> str:
    """Recover row-level lineage retained inside compiled JSONL/Parquet data."""

    candidates: list[object] = []
    if isinstance(metadata, dict):
        candidates.extend((metadata.get("logical_path"), metadata.get("path")))
        provenance = metadata.get("provenance")
        if isinstance(provenance, dict):
            candidates.extend(
                (
                    provenance.get("logical_path"),
                    provenance.get("path"),
                    provenance.get("source_path"),
                )
            )
    for candidate in candidates:
        if not isinstance(candidate, str):
            continue
        logical_path = candidate.strip().replace("\\", "/")
        if logical_path:
            return logical_path[:2048]
    return asset_logical_path


def _candidate_entropy(value: str) -> float:
    if not value:
        return 0.0
    counts = Counter(value)
    return -sum((count / len(value)) * math.log2(count / len(value)) for count in counts.values())


def _byte_entropy(data: bytes) -> float:
    if not data:
        return 0.0
    counts = Counter(data)
    entropy = -sum((count / len(data)) * math.log2(count / len(data)) for count in counts.values())
    return entropy / 8.0


def _secret_evidence(text: str) -> tuple[float, list[str]]:
    score = 0.0
    reasons: set[str] = set()
    for category, pattern, weight in _SECRET_PATTERNS:
        if pattern.search(text):
            score = max(score, weight)
            reasons.add(f"secret_candidate:{category}")
    for match in _SECRET_ASSIGNMENT_RE.finditer(text):
        if _candidate_entropy(match.group(1)) >= 3.5:
            score = max(score, 0.75)
            reasons.add("secret_candidate:high_entropy_assignment")
    return score, sorted(reasons)


def compact_metadata(metadata: object) -> dict[str, Any]:
    """Retain provenance-bearing metadata without duplicating full chat records."""

    if not isinstance(metadata, dict):
        return {}

    def compact_value(value: object, depth: int = 0) -> Any:
        if value is None or isinstance(value, (bool, int, float)):
            return value
        if isinstance(value, str):
            return value[:1024]
        if depth >= 3:
            return None
        if isinstance(value, dict):
            return {
                str(key)[:128]: compacted
                for key, item in list(value.items())[:64]
                if (compacted := compact_value(item, depth + 1)) is not None
            }
        if isinstance(value, list):
            return [
                compacted
                for item in value[:64]
                if (compacted := compact_value(item, depth + 1)) is not None
            ]
        return None

    compact: dict[str, Any] = {}
    for key, value in metadata.items():
        if key in {"messages", "conversations"} and isinstance(value, list):
            compact[f"{key}_count"] = len(value)
            compact[f"{key}_roles"] = [
                str(item.get("role") or item.get("from") or "")[:32]
                for item in value[:64]
                if isinstance(item, dict)
            ]
        else:
            compacted = compact_value(value)
            if compacted is not None:
                compact[str(key)[:128]] = compacted
    return compact


def document_mode(logical_path: str, format_name: str, metadata: dict[str, Any], domain: str) -> str:
    declared = metadata.get("cdas_mode")
    if declared in {"code", "natural", "structured"}:
        return str(declared)
    representation = metadata.get("representation")
    if representation in {"canonical_json", "table_row", "table_row_with_extra_fields"}:
        return "structured"
    if domain in {"code", "web"}:
        return "code"
    if format_name in {"csv", "tsv"}:
        return "structured"
    return "natural"


def artifact_roles(
    logical_path: str,
    *,
    mode: str,
    metadata: dict[str, Any],
    generated_score: float,
) -> list[str]:
    path = PurePosixPath(logical_path.replace("\\", "/"))
    parts = {part.casefold() for part in path.parts}
    name = path.name.casefold()
    suffix = path.suffix.casefold()
    stem = path.stem.casefold().replace("-", "_").replace(" ", "_")
    roles: set[str] = set()
    if "test" in parts or "tests" in parts or name.startswith("test_") or name.endswith("_test.py"):
        roles.add("code/test")
    elif mode == "code":
        roles.add("code/source")
    if suffix in _DOCUMENTATION_EXTENSIONS:
        roles.add("artifact/documentation")
    if any(stem == sidecar or stem.startswith(f"{sidecar}_") for sidecar in _SIDECAR_STEMS):
        roles.add("artifact/dataset-metadata")
    if suffix in _CONFIG_EXTENSIONS:
        roles.add("artifact/configuration")
    if mode == "structured":
        roles.add("artifact/structured-data")
    if mode == "natural":
        roles.add("artifact/natural-text")
    if suffix in {".diff", ".patch"}:
        roles.add("code/patch")
    if suffix == ".log":
        roles.add("artifact/log")
    if suffix in _WEB_ASSET_EXTENSIONS:
        roles.add("artifact/web-asset")
    if parts & _VENDORED_PARTS:
        roles.add("artifact/vendored")
    if parts & _GENERATED_PARTS or generated_score >= 0.5:
        roles.add("artifact/generated")
    if metadata.get("messages") or metadata.get("messages_count"):
        roles.add("artifact/conversation")
    return sorted(roles)


def asset_policy_reasons(profile: str, logical_path: str) -> list[str]:
    """Cheap, pre-extraction path policy for assets that are never data records.

    The dataset profile is intentionally different from the repository profile:
    CSS/SVG/XML may be useful source material in a code repository, but they are
    normally rendering/configuration sidecars beside HTML, Parquet, or JSONL
    dataset content.  Keeping this policy explicit prevents a trusted ``web``
    domain hint from bypassing corpus selection.
    """

    if profile not in SELECTION_PROFILES:
        raise ValueError(f"unknown selection profile {profile!r}")
    if profile == "preserve":
        return []
    path = PurePosixPath(logical_path.replace("\\", "/"))
    parts = {part.casefold() for part in path.parts}
    suffix = path.suffix.casefold()
    stem = path.stem.casefold().replace("-", "_").replace(" ", "_")
    reasons: list[str] = []
    if parts & _VENDORED_PARTS:
        reasons.append("cdas:path_vendored")
    if parts & _GENERATED_PARTS or path.name.casefold().endswith(".min.js"):
        reasons.append("cdas:path_generated")
    if profile in {"dataset", "strict"}:
        if any(stem == sidecar or stem.startswith(f"{sidecar}_") for sidecar in _SIDECAR_STEMS):
            reasons.append("cdas:path_dataset_metadata")
        if suffix in _CONFIG_EXTENSIONS or suffix in _WEB_ASSET_EXTENSIONS or suffix == ".log":
            reasons.append("cdas:path_dataset_sidecar")
    return sorted(set(reasons))


def analyze_document(
    text: str,
    *,
    logical_path: str,
    format_name: str,
    metadata: dict[str, Any],
    domain: str,
    max_chars: int = 20_000,
) -> tuple[dict[str, Any], list[str]]:
    """Build CDAS-style independent evidence and artifact-role labels."""

    sample = text[:max_chars]
    encoded = sample.encode("utf-8")
    tokens = [token.casefold() for token in _TOKEN_RE.findall(sample)]
    lines = sample.splitlines()
    nonempty = [line.strip() for line in lines if line.strip()]
    line_counts = Counter(nonempty)
    repeated = sum(count - 1 for count in line_counts.values() if count > 1)
    repeated_ratio = repeated / len(nonempty) if nonempty else 0.0
    long_ratio = sum(len(line) > 500 for line in nonempty) / len(nonempty) if nonempty else 0.0
    alphanumeric_ratio = sum(character.isalnum() for character in sample) / max(len(sample), 1)
    unique_ratio = len(set(tokens)) / len(tokens) if tokens else 0.0
    compression_ratio = len(zlib.compress(encoded, level=6)) / max(len(encoded), 1)
    lower = sample.casefold()
    normalized_path = logical_path.replace("\\", "/").casefold()
    path_parts = set(PurePosixPath(normalized_path).parts)
    marker_hits = sorted(marker for marker in _GENERATED_MARKERS if marker in lower[:4096])
    generated_score = _clamp(
        0.7 * bool(marker_hits)
        + 0.55 * bool(path_parts & _GENERATED_PARTS)
        + 0.45 * normalized_path.endswith(".min.js")
        + 0.35 * (long_ratio >= 0.5 and alphanumeric_ratio >= 0.6)
    )
    boilerplate_hits = sorted(marker for marker in _BOILERPLATE_MARKERS if marker in lower)
    boilerplate_score = _clamp(
        repeated_ratio * 0.8
        + min(0.4, len(boilerplate_hits) * 0.2)
        + (0.2 if compression_ratio < 0.2 and len(encoded) > 256 else 0.0)
    )
    truncation_reasons: list[str] = []
    truncation_score = 0.0
    if text and not text.endswith(("\n", "\r")):
        truncation_reasons.append("missing_terminal_newline")
        truncation_score += 0.15
    mode = document_mode(logical_path, format_name, metadata, domain)
    if mode == "code":
        if any(text.count(left) != text.count(right) for left, right in (("(", ")"), ("[", "]"), ("{", "}"))):
            truncation_reasons.append("unbalanced_delimiters")
            truncation_score += 0.6
        if text.rstrip().endswith(("\\", ",", "=", "+", "-", "*", "/")):
            truncation_reasons.append("abrupt_terminal_token")
            truncation_score += 0.35
    hygiene_reasons: list[str] = []
    if not text.strip():
        hygiene_reasons.append("empty_content")
    if 0 < len(text.strip()) < 32:
        hygiene_reasons.append("very_short_content")
    if repeated_ratio >= 0.5:
        hygiene_reasons.append("high_repetition")
    if long_ratio >= 0.5:
        hygiene_reasons.append("very_long_lines")
    if "\ufffd" in text:
        hygiene_reasons.append("replacement_characters")
    secret_score, secret_reasons = _secret_evidence(sample)
    signals = {
        "signal_version": QUALITY_SIGNAL_VERSION,
        "mode": mode,
        "utf8_bytes": len(text.encode("utf-8")),
        "line_count": len(lines),
        "token_count": len(tokens),
        "unique_token_ratio": round(unique_ratio, 6),
        "byte_entropy": round(_byte_entropy(encoded), 6),
        "compression_ratio": round(compression_ratio, 6),
        "repeated_line_ratio": round(repeated_ratio, 6),
        "long_line_ratio": round(long_ratio, 6),
        "alphanumeric_ratio": round(alphanumeric_ratio, 6),
        "generated_likelihood": round(generated_score, 6),
        "boilerplate_likelihood": round(boilerplate_score, 6),
        "truncation_likelihood": round(_clamp(truncation_score), 6),
        "secret_risk": round(secret_score, 6),
        "hygiene_reasons": hygiene_reasons,
        "generated_markers": marker_hits,
        "boilerplate_markers": boilerplate_hits,
        "truncation_reasons": truncation_reasons,
        "secret_reasons": secret_reasons,
        "compatibility_fold_would_change": unicodedata.normalize("NFKC", text)
        != unicodedata.normalize("NFC", text),
    }
    roles = artifact_roles(
        logical_path,
        mode=mode,
        metadata=metadata,
        generated_score=generated_score,
    )
    return signals, roles


def profile_quarantine_reasons(profile: str, signals: dict[str, Any], roles: list[str]) -> list[str]:
    if profile not in SELECTION_PROFILES:
        raise ValueError(f"unknown selection profile {profile!r}")
    if profile == "preserve":
        return []
    role_set = set(roles)
    reasons: list[str] = []
    if float(signals.get("secret_risk") or 0.0) >= 0.75:
        reasons.append("cdas:secret_risk")
    if role_set & {"artifact/generated", "artifact/vendored"}:
        reasons.append("cdas:generated_or_vendored")
    if profile in {"dataset", "strict"}:
        if "artifact/dataset-metadata" in role_set:
            reasons.append("cdas:dataset_metadata")
        if role_set & {"artifact/configuration", "artifact/log", "artifact/web-asset"}:
            reasons.append("cdas:dataset_sidecar")
    if profile == "strict":
        if float(signals.get("boilerplate_likelihood") or 0.0) >= 0.55:
            reasons.append("cdas:boilerplate")
        if "high_repetition" in signals.get("hygiene_reasons", []):
            reasons.append("cdas:high_repetition")
    return sorted(set(reasons))


@dataclass(frozen=True, slots=True)
class AssetObservation:
    asset_id: str
    source_id: str
    logical_path: str
    raw_sha256: str
    byte_size: int
    modified_ns: int
    format_name: str
    media_type: str
    adapter_name: str


class CorpusCatalog:
    """Batched per-corpus inventory; never queried on the training hot path."""

    def __init__(self, path: Path, *, source_root: Path, source_name: str) -> None:
        self.path = path
        self.source_root = source_root.resolve()
        self.source_id = stable_identity("src", str(self.source_root))
        self.connection = sqlite3.connect(path)
        self.connection.execute("PRAGMA journal_mode=WAL")
        self.connection.execute("PRAGMA synchronous=NORMAL")
        self.connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS sources(
              source_id TEXT PRIMARY KEY, schema_version INTEGER NOT NULL,
              name TEXT NOT NULL, root TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS assets(
              asset_id TEXT PRIMARY KEY, schema_version INTEGER NOT NULL,
              source_id TEXT NOT NULL, logical_path TEXT NOT NULL,
              raw_sha256 TEXT NOT NULL, byte_size INTEGER NOT NULL,
              modified_ns INTEGER NOT NULL, format_name TEXT NOT NULL,
              media_type TEXT NOT NULL, adapter_name TEXT NOT NULL,
              status TEXT NOT NULL, reason_codes_json TEXT NOT NULL,
              documents_seen INTEGER NOT NULL DEFAULT 0,
              documents_kept INTEGER NOT NULL DEFAULT 0
            );
            CREATE TABLE IF NOT EXISTS documents(
              document_id TEXT PRIMARY KEY, schema_version INTEGER NOT NULL,
              source_id TEXT NOT NULL, asset_id TEXT NOT NULL, locator TEXT NOT NULL,
              normalized_sha256 TEXT NOT NULL, training_sha256 TEXT NOT NULL,
              utf8_bytes INTEGER NOT NULL, domain TEXT NOT NULL, language TEXT NOT NULL,
              selection TEXT NOT NULL, reason_codes_json TEXT NOT NULL,
              roles_json TEXT NOT NULL, signals_json TEXT NOT NULL,
              metadata_json TEXT NOT NULL, transformation_json TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS issues(
              issue_id INTEGER PRIMARY KEY AUTOINCREMENT, asset_id TEXT,
              locator TEXT NOT NULL, reason_code TEXT NOT NULL, detail TEXT NOT NULL
            );
            CREATE INDEX IF NOT EXISTS documents_selection ON documents(selection);
            CREATE INDEX IF NOT EXISTS documents_normalized ON documents(normalized_sha256);
            CREATE INDEX IF NOT EXISTS documents_asset ON documents(asset_id);
            """
        )
        self.connection.execute(f"PRAGMA user_version={CATALOG_SCHEMA_VERSION}")
        self.connection.execute(
            "INSERT OR REPLACE INTO sources VALUES(?,?,?,?)",
            (self.source_id, CORPUS_SCHEMA_VERSION, source_name, str(self.source_root)),
        )
        self.connection.commit()
        self._documents: list[tuple[Any, ...]] = []
        self.selection_counts: Counter[str] = Counter()
        self.role_counts: Counter[str] = Counter()
        self.kept_role_counts: Counter[str] = Counter()
        self.reason_counts: Counter[str] = Counter()
        self.asset_document_counts: Counter[str] = Counter()
        self.asset_kept_counts: Counter[str] = Counter()
        self.compatibility_fold_would_change_docs = 0
        self.closed = False

    def describe_asset(
        self,
        path: Path,
        *,
        adapter_name: str = "",
        hash_contents: bool = True,
    ) -> AssetObservation:
        """Build an asset observation without touching the catalog database."""

        resolved = path.resolve()
        try:
            logical = resolved.relative_to(self.source_root).as_posix()
        except ValueError:
            logical = resolved.name
        stat = resolved.stat()
        format_name = adapter_name or resolved.suffix.casefold().lstrip(".") or "unknown"
        media_type = mimetypes.guess_type(resolved.name)[0] or "application/octet-stream"
        return AssetObservation(
            asset_id=stable_identity("asset", self.source_id, logical),
            source_id=self.source_id,
            logical_path=logical,
            raw_sha256=digest_file(resolved) if hash_contents else "",
            byte_size=int(stat.st_size),
            modified_ns=int(stat.st_mtime_ns),
            format_name=format_name,
            media_type=media_type,
            adapter_name=adapter_name,
        )

    def record_asset(self, observation: AssetObservation) -> AssetObservation:
        adapter_name = observation.adapter_name
        self.connection.execute(
            """INSERT OR REPLACE INTO assets(
              asset_id,schema_version,source_id,logical_path,raw_sha256,byte_size,
              modified_ns,format_name,media_type,adapter_name,status,reason_codes_json,
              documents_seen,documents_kept) VALUES(?,?,?,?,?,?,?,?,?,?,?,?,0,0)""",
            (
                observation.asset_id,
                CORPUS_SCHEMA_VERSION,
                observation.source_id,
                observation.logical_path,
                observation.raw_sha256,
                observation.byte_size,
                observation.modified_ns,
                observation.format_name,
                observation.media_type,
                observation.adapter_name,
                "processing" if adapter_name else "inventory_only",
                "[]" if adapter_name else '["adapter_unavailable"]',
            ),
        )
        return observation

    def observe_asset(
        self,
        path: Path,
        *,
        adapter_name: str = "",
        hash_contents: bool = True,
    ) -> AssetObservation:
        return self.record_asset(
            self.describe_asset(path, adapter_name=adapter_name, hash_contents=hash_contents)
        )

    def record_issue(self, asset_id: str | None, locator: str, reason_code: str, detail: str) -> None:
        self.connection.execute(
            "INSERT INTO issues(asset_id,locator,reason_code,detail) VALUES(?,?,?,?)",
            (asset_id, locator, reason_code, detail[:2000]),
        )

    def record_document(
        self,
        *,
        asset: AssetObservation,
        locator: str,
        training_text: str | None,
        domain: str,
        language: str,
        selection: str,
        reasons: list[str],
        roles: list[str],
        signals: dict[str, Any],
        metadata: dict[str, Any],
        source_text: str | None = None,
        source_sha256: str | None = None,
        source_utf8_bytes: int | None = None,
        training_sha256: str | None = None,
        signals_json: str | None = None,
        roles_json: str | None = None,
        metadata_json: str | None = None,
    ) -> None:
        """Record one selection decision.

        Callers may pass digests and JSON columns precomputed elsewhere (a
        worker process) instead of ``source_text``/``metadata``; the stored
        values are identical either way.
        """

        if source_sha256 is None or source_utf8_bytes is None:
            if source_text is None:
                raise ValueError("record_document needs source_text or its precomputed digest")
            source_sha256, source_utf8_bytes = source_digest(source_text)
        if training_sha256 is None:
            training_sha256 = digest_text(training_text) if training_text is not None else ""
        if signals_json is None:
            signals_json = json.dumps(signals, ensure_ascii=False, separators=(",", ":"))
        if roles_json is None:
            roles_json = json.dumps(roles, ensure_ascii=False, separators=(",", ":"))
        if metadata_json is None:
            metadata_json = json.dumps(
                compact_metadata(metadata), ensure_ascii=False, separators=(",", ":")
            )
        document_id = stable_identity("doc", asset.asset_id, locator)
        transformations = {
            "source_normalization_version": SOURCE_NORMALIZATION_VERSION,
            "source_normalization": ["utf8_bom", "newline"],
            "training_normalization": "nfc_whitespace_v2",
        }
        self._documents.append(
            (
                document_id,
                CORPUS_SCHEMA_VERSION,
                asset.source_id,
                asset.asset_id,
                locator,
                source_sha256,
                training_sha256,
                int(source_utf8_bytes),
                domain,
                language,
                selection,
                json.dumps(sorted(set(reasons)), ensure_ascii=False, separators=(",", ":")),
                roles_json,
                signals_json,
                metadata_json,
                json.dumps(transformations, ensure_ascii=False, separators=(",", ":")),
            )
        )
        self.selection_counts[selection] += 1
        self.asset_document_counts[asset.asset_id] += 1
        if selection == "kept":
            self.asset_kept_counts[asset.asset_id] += 1
        self.role_counts.update(roles)
        if selection == "kept":
            self.kept_role_counts.update(roles)
        self.reason_counts.update(reasons)
        if signals.get("compatibility_fold_would_change"):
            self.compatibility_fold_would_change_docs += 1
        if len(self._documents) >= 4096:
            self.flush()

    def finish_asset(
        self,
        asset: AssetObservation,
        *,
        status: str,
        reasons: list[str] | None = None,
        documents_seen: int = 0,
        documents_kept: int = 0,
    ) -> None:
        self.connection.execute(
            """UPDATE assets SET status=?,reason_codes_json=?,documents_seen=?,documents_kept=?
               WHERE asset_id=?""",
            (
                status,
                json.dumps(sorted(set(reasons or [])), separators=(",", ":")),
                documents_seen,
                documents_kept,
                asset.asset_id,
            ),
        )

    def flush(self) -> None:
        if self._documents:
            self.connection.executemany(
                "INSERT OR REPLACE INTO documents VALUES(?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)",
                self._documents,
            )
            self._documents.clear()
        if self.asset_document_counts:
            self.connection.executemany(
                "UPDATE assets SET documents_seen=?,documents_kept=? WHERE asset_id=?",
                (
                    (
                        count,
                        self.asset_kept_counts.get(asset_id, 0),
                        asset_id,
                    )
                    for asset_id, count in self.asset_document_counts.items()
                ),
            )
        self.connection.commit()

    def summary(self) -> dict[str, Any]:
        self.flush()
        assets = int(self.connection.execute("SELECT COUNT(*) FROM assets").fetchone()[0])
        issues = int(self.connection.execute("SELECT COUNT(*) FROM issues").fetchone()[0])
        documents = sum(self.selection_counts.values())
        excluded = documents - self.selection_counts.get("kept", 0)
        return {
            "schema_version": CORPUS_SCHEMA_VERSION,
            "catalog_schema_version": CATALOG_SCHEMA_VERSION,
            "quality_signal_version": QUALITY_SIGNAL_VERSION,
            "source_normalization_version": SOURCE_NORMALIZATION_VERSION,
            "source_id": self.source_id,
            "catalog": self.path.name,
            "assets": assets,
            "documents": documents,
            "issues": issues,
            "selection_counts": dict(sorted(self.selection_counts.items())),
            "reason_counts": dict(self.reason_counts.most_common()),
            "role_counts": dict(self.role_counts.most_common()),
            "kept_role_counts": dict(self.kept_role_counts.most_common()),
            "excluded_fraction": round(excluded / max(documents, 1), 6),
            "compatibility_fold_would_change_docs": self.compatibility_fold_would_change_docs,
            "provenance": PORT_PROVENANCE,
        }

    def close(self) -> None:
        if self.closed:
            return
        self.flush()
        self.connection.close()
        self.closed = True
